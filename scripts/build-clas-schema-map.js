import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const trustSchemaRoot = path.resolve(__dirname, '../schemas/clas/trust-verification');
const executionSchemaPath = path.resolve(__dirname, '../schemas/clas/execution/execution.receipt.schema.json');
const outputPath = path.resolve(__dirname, '../src/generated/clas-schema-map.js');

const TRUST_VERBS = ['verify','authenticate','authorize','attest','sign','permit','grant','approve','reject','endorse'];

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, 'utf8'));
}

function bundleRefs(schema, currentDir, cache) {
  if (Array.isArray(schema)) return schema.map((s) => bundleRefs(s, currentDir, cache));
  if (!schema || typeof schema !== 'object') return schema;
  if (typeof schema.$ref === 'string' && schema.$ref.startsWith('.')) {
    const refPath = path.resolve(currentDir, schema.$ref);
    if (!cache.has(refPath)) throw new Error(`Unresolved $ref: ${schema.$ref} from ${currentDir}`);
    return bundleRefs(cache.get(refPath), path.dirname(refPath), cache);
  }
  const out = {};
  for (const [k,v] of Object.entries(schema)) out[k] = bundleRefs(v, currentDir, cache);
  return out;
}

async function main() {
  const proofPath = path.join(trustSchemaRoot, '_shared/proof.schema.json');
  const tracePath = path.join(trustSchemaRoot, '_shared/trace.schema.json');
  const basePath = path.join(trustSchemaRoot, 'verbs/receipt.base.schema.json');

  const proof = await readJson(proofPath);
  const trace = await readJson(tracePath);
  const base = await readJson(basePath);
  const executionReceiptSchema = await readJson(executionSchemaPath);

  const cache = new Map([[proofPath, proof], [tracePath, trace], [basePath, base]]);
  const bundledBase = bundleRefs(base, path.dirname(basePath), cache);

  const schemaMap = Object.fromEntries(TRUST_VERBS.map((verb) => [verb, {
    receipt: {
      ...structuredClone(bundledBase),
      properties: {
        ...bundledBase.properties,
        verb: { type: 'string', const: verb }
      }
    }
  }]));

  const out = `// AUTO-GENERATED by scripts/build-clas-schema-map.js\nexport const TRUST_VERBS = ${JSON.stringify(TRUST_VERBS, null, 2)};\n\nexport const clasSchemaMap = ${JSON.stringify(schemaMap, null, 2)};\n\nexport const CLAS_EXECUTION_RECEIPT_SCHEMA = ${JSON.stringify(executionReceiptSchema, null, 2)};\n`;
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, out);
  console.log(`Wrote ${outputPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
